function choices(ep,side) {
  add(`${D.sides[side]} — ${ep.leaders[side]}`, `Брифинг: ${ep.briefs[side]}`);
  ep.choices[side].forEach((c,i) => {
    add(`${i+1}. ${c.title}`, `Действие: ${c.detail}`, `Зачем: ${c.why || c.detail}`,
      `Направление: ${c.historical ? 'историческое' : 'альтернативное'}.`,
      `Последствие: ${c.outcome}`, `Базовые шкалы: ${values(c.delta)}.`,
      `Явные стратегические эффекты: ${values(c.strategic)}.`,
      `Метка: ${c.tag || 'нет'}; политика: ${c.policy || 'нет'}; прямое столкновение: ${c.war ? 'да' : 'нет'}.`);
    const requirements = {...c.requires,...c.requiresStrategic};
    add(`Условия: ${Object.entries(requirements).map(([k,v])=>`${labels[k]} ≥ ${v}`).join('; ') || 'нет'}${c.requiresReforms ? `; этапы подготовки ≥ ${c.requiresReforms}` : ''}.`);
    if(c.set) add(`Установка сюжетных признаков: ${JSON.stringify(c.set)}.`);
    add('');
  });
}
function exposition(ep) {
  add(`Контекст: ${ep.context}`, `Как мы здесь оказались: ${ep.exposition.origin}`, 'Интересы сторон:',
    ...ep.exposition.interests.map(t=>`— ${t}`), `Почему важно: ${ep.exposition.stakes}`, '');
}
